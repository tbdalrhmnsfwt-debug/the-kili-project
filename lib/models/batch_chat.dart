/// Local chat messages and their cursor.
library;

/// Text or a voice note.
enum ChatMessageKind { text, voice }

/// A page cursor ordered by creation time and then id.
class ChatCursor {
  const ChatCursor({required this.createdAt, required this.id});

  final DateTime createdAt;
  final String id;

  int compareTo(ChatCursor other) {
    final byTime = createdAt.compareTo(other.createdAt);
    return byTime != 0 ? byTime : id.compareTo(other.id);
  }

  Map<String, dynamic> toJson() => {
        'createdAt': createdAt.toIso8601String(),
        'id': id,
      };

  factory ChatCursor.fromJson(Map<String, dynamic> json) => ChatCursor(
        createdAt: DateTime.tryParse(json['createdAt'] as String? ?? '') ??
            DateTime.fromMillisecondsSinceEpoch(0),
        id: json['id'] as String? ?? '',
      );
}

/// A page of messages plus whether older ones remain.
///
/// [messages] is ordered oldest to newest so the list can be appended to the
/// top without reversing it again.
class ChatPage {
  const ChatPage({required this.messages, required this.hasMore});

  final List<ChatMessage> messages;
  final bool hasMore;
}

/// One message in a batch channel.
class ChatMessage {
  const ChatMessage({
    required this.id,
    required this.batchId,
    required this.channelId,
    required this.authorUid,
    required this.authorName,
    required this.kind,
    required this.createdAt,
    this.text = '',
    this.voiceFileName = '',
    this.voiceDurationMs,
    this.replyToId,
    this.editedAt,
    this.deletedAt,
    this.reactions = const {},
    this.pinned = false,
    this.clientKey = '',
  });

  final String id;
  final String batchId;
  final String channelId;
  final String authorUid;
  final String authorName;
  final ChatMessageKind kind;
  final String text;
  final String voiceFileName;
  final int? voiceDurationMs;
  final String? replyToId;
  final DateTime createdAt;
  final DateTime? editedAt;
  final DateTime? deletedAt;

  /// Emoji -> uids that reacted. A uid appears at most once per emoji.
  final Map<String, Set<String>> reactions;
  final bool pinned;

  /// Idempotency key generated by the sender.
  final String clientKey;

  bool get isDeleted => deletedAt != null;

  ChatMessage copyWith({
    String? text,
    DateTime? editedAt,
    DateTime? deletedAt,
    Map<String, Set<String>>? reactions,
    bool? pinned,
  }) =>
      ChatMessage(
        id: id,
        batchId: batchId,
        channelId: channelId,
        authorUid: authorUid,
        authorName: authorName,
        kind: kind,
        text: text ?? this.text,
        voiceFileName: voiceFileName,
        voiceDurationMs: voiceDurationMs,
        replyToId: replyToId,
        createdAt: createdAt,
        editedAt: editedAt ?? this.editedAt,
        deletedAt: deletedAt ?? this.deletedAt,
        reactions: reactions ?? this.reactions,
        pinned: pinned ?? this.pinned,
        clientKey: clientKey,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'batchId': batchId,
        'channelId': channelId,
        'authorUid': authorUid,
        'authorName': authorName,
        'kind': kind.name,
        'text': text,
        if (voiceFileName.isNotEmpty) 'voiceFileName': voiceFileName,
        if (voiceDurationMs != null) 'voiceDurationMs': voiceDurationMs,
        if (replyToId != null) 'replyToId': replyToId,
        'createdAt': createdAt.toIso8601String(),
        if (editedAt != null) 'editedAt': editedAt!.toIso8601String(),
        if (deletedAt != null) 'deletedAt': deletedAt!.toIso8601String(),
        if (reactions.isNotEmpty)
          'reactions': {
            for (final entry in reactions.entries)
              entry.key: entry.value.toList(),
          },
        'pinned': pinned,
        if (clientKey.isNotEmpty) 'clientKey': clientKey,
      };

  factory ChatMessage.fromJson(Map<String, dynamic> json) => ChatMessage(
        id: json['id'] as String? ?? '',
        batchId: json['batchId'] as String? ?? '',
        channelId: json['channelId'] as String? ?? 'main',
        authorUid: json['authorUid'] as String? ?? '',
        authorName: json['authorName'] as String? ?? '',
        kind: switch (json['kind'] as String?) {
          'voice' => ChatMessageKind.voice,
          _ => ChatMessageKind.text,
        },
        text: json['text'] as String? ?? '',
        voiceFileName: json['voiceFileName'] as String? ?? '',
        voiceDurationMs: (json['voiceDurationMs'] as num?)?.toInt(),
        replyToId: json['replyToId'] as String?,
        createdAt: DateTime.tryParse(json['createdAt'] as String? ?? '') ??
            DateTime.fromMillisecondsSinceEpoch(0),
        editedAt: DateTime.tryParse(json['editedAt'] as String? ?? ''),
        deletedAt: DateTime.tryParse(json['deletedAt'] as String? ?? ''),
        reactions: {
          if (json['reactions'] is Map)
            for (final entry in (json['reactions'] as Map).entries)
              '${entry.key}': {...?(entry.value as List?)?.whereType<String>()},
        },
        pinned: json['pinned'] as bool? ?? false,
        clientKey: json['clientKey'] as String? ?? '',
      );
}
